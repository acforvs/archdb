"""archdb command line: validate, check-sources, count-params, build, serve."""

from __future__ import annotations

import argparse
import functools
import http.server
import json
import shutil
import sys

import yaml

from . import export
from .data import ROOT, Loader, load_fields, load_models, load_orgs, validate
from .export import dataset

SITE = ROOT / "site"
PUBLIC = ROOT / "web" / "public"
EXPORTS = ROOT / "exports"


class NoCacheHandler(http.server.SimpleHTTPRequestHandler):
    """Revalidate local files after a rebuild."""

    def end_headers(self) -> None:
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()


def build(check: bool = False) -> None:
    groups, fields = load_fields()
    models = load_models()
    errors = validate(models, fields)
    if errors:
        sys.exit("\n".join(errors))
    data = dataset(models, groups, fields, load_orgs())
    stale = export.write(data, EXPORTS, check=check)
    if check:
        if stale:
            sys.exit(f"exports/ is out of date ({', '.join(stale)}): run `uv run archdb build`")
        print("exports/ is up to date")
        return
    PUBLIC.mkdir(parents=True, exist_ok=True)
    (PUBLIC / "data.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))
    for name in ("models.csv", "facts.csv", "stages.csv", "fields.csv"):
        shutil.copyfile(EXPORTS / name, PUBLIC / name)
    shutil.copyfile(ROOT / "LICENSE-DATA", PUBLIC / "LICENSE-DATA")
    from .pages import write

    write(data, PUBLIC, ROOT / "web/.generated")
    print(
        f"{len(models)} models: wrote exports/ and web/public/"
        + (f" (changed: {', '.join(stale)})" if stale else "")
    )


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(prog="archdb")
    sub = parser.add_subparsers(dest="cmd", required=True)
    val = sub.add_parser("validate", help="check records against the field registry")
    val.add_argument("models", nargs="*", help="model ids (default: all)")
    check = sub.add_parser("check-sources", help="fetch cited sources; verify config pointers and quotes")
    check.add_argument("models", nargs="*", help="model ids (default: all)")
    cp = sub.add_parser(
        "count-params", help="count parameters from checkpoint headers into data/param_counts.yaml"
    )
    cp.add_argument("models", nargs="*", help="model ids (default: all with a Hugging Face config)")
    b = sub.add_parser("build", help="write exports/ (CSV, JSON) and the website data")
    b.add_argument("--check", action="store_true", help="fail if exports/ is not up to date")
    serve = sub.add_parser("serve", help="serve the built site (npm --prefix web run build) on localhost")
    serve.add_argument("--port", type=int, default=8000)
    args = parser.parse_args(argv)

    if args.cmd == "validate":
        _, fields = load_fields()
        models = [m for m in load_models() if not args.models or m.id in args.models]
        errors = validate(models, fields)
        print("\n".join(errors) or f"{len(models)} models, {sum(len(m.facts) for m in models)} facts: ok")
        sys.exit(1 if errors else 0)
    if args.cmd == "check-sources":
        from .sources import check_model, check_orgs, coverage, ignored_config_keys

        totals, failed = {"pointer_ok": 0, "quote_ok": 0, "unchecked": 0}, []
        ignore = ignored_config_keys()
        models = [m for m in load_models() if not args.models or m.id in args.models]
        if not args.models:
            failed += check_orgs(load_orgs())
        for m in models:
            problems, stats = check_model(m)
            failed += problems + coverage(m, ignore)
            for k in totals:
                totals[k] += stats[k]
        print("\n".join(failed))
        print(
            f"{totals['pointer_ok']} config pointers and {totals['quote_ok']} quotes verified; "
            f"{totals['unchecked']} facts have neither; {len(failed)} problems"
        )
        sys.exit(1 if failed else 0)
    if args.cmd == "count-params":
        from .checkpoint import PARTS, count

        path = ROOT / "data" / "param_counts.yaml"
        counts = yaml.load(path.read_text(), Loader) or {} if path.exists() else {}
        head = "# Parameter counts by part from released checkpoints' safetensors headers.\n"
        head += "# Generated by `uv run archdb count-params`; do not edit.\n"
        failed = []
        for m in load_models():
            if args.models and m.id not in args.models:
                continue
            try:
                c = count(m)
            except OSError as e:
                failed.append(f"{m.id}: {e}")
                continue
            if c:
                counts[m.id] = c
                path.write_text(head + yaml.safe_dump(dict(sorted(counts.items())), sort_keys=False))
                print(f"{m.id}: {sum(c[p] for p in PARTS) / 1e9:.1f}B in checkpoint")
        print("\n".join(failed))
        sys.exit(1 if failed else 0)
    if args.cmd == "build":
        build(check=args.check)
    if args.cmd == "serve":
        if not (SITE / "index.html").exists():
            sys.exit("site/ is missing: run `uv run archdb build && npm --prefix web run build` first")
        handler = functools.partial(NoCacheHandler, directory=str(SITE))
        print(f"http://127.0.0.1:{args.port}")
        http.server.ThreadingHTTPServer(("127.0.0.1", args.port), handler).serve_forever()


if __name__ == "__main__":
    main()
